namespace grandvm {
    struct unkopcode { uint8_t op; size_t ip; };

    class VM {
    public:
        VM(const uint8_t* code, size_t code_len, uint8_t* buf, int32_t len, int32_t seed)
            : code_(code), code_len_(code_len), ip_(0) {
            opstack_.assign(16384, 0);
            locals_.assign(8192, 0);
            sp_ = 0;
            a1_ = reinterpret_cast<int64_t>(buf);
            a2_ = len;
            a3_ = seed;
        }

        void run() {
            const size_t n = code_len_;
            while (ip_ < n) {
                uint8_t op = code_[ip_];
                size_t start_ip = ip_;
                ip_ += 1;
                switch (op) {
                // U8_TRUNC_I32: top32 = (uint8_t)top32
                case 0x0C: { int32_t v = top_i32(); top_i32() = (uint8_t)v; break; }
                // SUB_I64: below64 = below64 - top64; pop
                case 0x0E: { int64_t t = top_i64(), b = below_i64(); below_i64() = b - t; pop(8); break; }
                // U8_MASK_I32: top32 &= 0xFF (identical to 0x0C by effect)
                case 0x11: { uint8_t v = (uint8_t)top_i32(); top_i32() = v; break; }
                // STORE_I64: *(int64_t*)ptr = value; ptr = below, value = top; pop 16
                case 0x1B: { int64_t value = top_i64(), ptr = below_i64(); *reinterpret_cast<int64_t*>(ptr) = value; pop(16); break; }
                // LOAD_I64: top = *(int64_t*)top
                case 0x1D: { int64_t ptr = top_i64(); top_i64() = *reinterpret_cast<int64_t*>(ptr); break; }
                // PUSH_I32_CONST (imm32): push zero-extended 32-bit immediate
                case 0x21: case 0xDF: { int32_t val = read_i32_operand(); ip_ += 4; push_i64(0); top_i32() = val; break; }
                // ADD_I64: below64 = below64 + top64; pop
                case 0x25: { int64_t t = top_i64(), b = below_i64(); below_i64() = b + t; pop(8); break; }
                // XOR_I32: below32 = below32 ^ top32; pop
                case 0x31: case 0xD1: { int32_t t = top_i32(), b = below_i32(); below_i32() = b ^ t; pop(8); break; }
                // LOAD_I32: top32 = *(int32_t*)top_ptr
                case 0x34: { int64_t ptr = top_i64(); top_i32() = *reinterpret_cast<int32_t*>(ptr); break; }
                // UMOD_I32: below32 = (uint32_t)below32 % (uint32_t)top32; pop
                case 0x3A: { uint32_t t = (uint32_t)top_i32(), b = (uint32_t)below_i32(); if (t == 0) throw std::runtime_error("mod by zero"); below_i32() = (int32_t)(b % t); pop(8); break; }
                // LOAD_U8: top32 = *(uint8_t*)top_ptr (zero-extend byte to i32)
                case 0x43: { int64_t ptr = top_i64(); top_i32() = *reinterpret_cast<uint8_t*>(ptr); break; }
                // ADD_I32: below32 = below32 + top32; pop
                case 0x46: { int32_t t = top_i32(), b = below_i32(); below_i32() = b + t; pop(8); break; }
                // JMP_IF_NZ (imm32 disp): pop cond; if (cond != 0) ip += disp else skip disp
                case 0x4A: { int32_t cond = top_i32(); pop(8); int32_t disp = read_i32_operand(); if (cond != 0) ip_ += disp; else ip_ += 4; break; }
                // OR_I32: below32 = below32 | top32; pop
                case 0x53: { int32_t t = top_i32(), b = below_i32(); below_i32() = b | t; pop(8); break; }
                // UDIV_I32_SWAPPED: below32 = top32 / below32 (division with swapped operands); pop
                case 0x58: { uint32_t t = (uint32_t)top_i32(), b = (uint32_t)below_i32(); if (b == 0) throw std::runtime_error("division by zero"); below_i32() = (int32_t)(t / b); pop(8); break; }
                // RET: halt VM
                case 0x67: { return; }
                // NOP: no-op (skip)
                case 0x6C: case 0xE3: break;
                // ZEXT_I32_TO_I64: top64 = (uint32_t)top32 (zero-extend)
                case 0x71: { uint32_t v = (uint32_t)top_i32(); top_i64() = (int64_t)(uint64_t)v; break; }
                // MUL_I64: below64 = below64 * top64; pop
                case 0x7A: { int64_t t = top_i64(), b = below_i64(); below_i64() = b * t; pop(8); break; }
                // LEA_LOCAL (imm32 offs): push &locals_[locals + offs]
                case 0x84: { int32_t offs = read_i32_operand(); ip_ += 4; int64_t addr = reinterpret_cast<int64_t>(locals_.data() + locals + offs); push_i64(addr); break; }
                // U8_TRUNC (alias of 0x0C)
                case 0x8C: { int32_t v = top_i32(); top_i32() = (uint8_t)v; break; }
                // ULT_I64: below32 = (u64)below64 < (u64)top64 ? 1 : 0; pop
                case 0x94: { uint64_t t = (uint64_t)top_i64(), b = (uint64_t)below_i64(); below_i32() = (b < t) ? 1 : 0; pop(8); break; }
                // MUL_I32: below32 = below32 * top32; pop
                case 0x98: { int32_t t = top_i32(), b = below_i32(); below_i32() = b * t; pop(8); break; }
                // STORE_U8: *(uint8_t*)ptr = (uint8_t)value; ptr = top, value = below; pop 16
                case 0x9C: { int64_t ptr = top_i64(); int32_t value = below_i32(); *reinterpret_cast<uint8_t*>(ptr) = (uint8_t)value; pop(16); break; }
                // JMP (imm32 disp): unconditional relative jump
                case 0xA4: { int32_t disp = read_i32_operand(); ip_ += disp; break; }
                // SEXT_I32_TO_I64: top64 = (int64_t)(int32_t)top32
                case 0xAD: { int32_t v = top_i32(); top_i64() = (int64_t)v; break; }
                // ULT_I32_SWAPPED: below32 = (u32)top32 < (u32)below32 ? 1 : 0; pop  (note: operands compared in reverse order)
                case 0xAE: { uint32_t t = (uint32_t)top_i32(), b = (uint32_t)below_i32(); below_i32() = (t < b) ? 1 : 0; pop(8); break; }
                // LEA_PARAM (imm32 sel): push address of vm parameter (0=&a1 buf ptr, 1=&a2 len, 2=&a3 seed)
                case 0xBC: {
                    int32_t sel = read_i32_operand(); ip_ += 4;
                    int64_t addr;
                    if (sel == 0) addr = reinterpret_cast<int64_t>(&a1_);
                    else if (sel == 1) addr = reinterpret_cast<int64_t>(&a2_);
                    else if (sel == 2) addr = reinterpret_cast<int64_t>(&a3_);
                    else throw std::runtime_error("bad param selector");
                    push_i64(addr);
                    break;
                }
                // SHL_I32: below32 = (uint32_t)below32 << (top32 & 31); pop
                case 0xC3: { int32_t t = top_i32(), b = below_i32(); below_i32() = (int32_t)((uint32_t)b << (t & 31)); pop(8); break; }
                // AND_I32: below32 = below32 & top32; pop
                case 0xC6: { int32_t t = top_i32(), b = below_i32(); below_i32() = b & t; pop(8); break; }
                // STORE_I32: *(int32_t*)ptr = value; ptr = top, value = below; pop 16
                case 0xD3: { int64_t ptr = top_i64(); int32_t value = below_i32(); *reinterpret_cast<int32_t*>(ptr) = value; pop(16); break; }
                // PUSH_I64_CONST (imm64): push 64-bit immediate
                case 0xF1: { int64_t val = read_i64_operand(); ip_ += 8; push_i64(val); break; }
                default:
                    throw unkopcode{ op, start_ip };
                }
            }
        }
    private:
        static const int32_t locals = 4096;
        const uint8_t* code_;
        size_t code_len_;
        size_t ip_;
        std::vector<uint8_t> opstack_;
        size_t sp_;
        std::vector<uint8_t> locals_;
        int64_t a1_;
        int32_t a2_;
        int32_t a3_;

        int32_t read_i32_operand() { int32_t v; memcpy(&v, code_ + ip_, 4); return v; }
        int64_t read_i64_operand() { int64_t v; memcpy(&v, code_ + ip_, 8); return v; }
        int64_t& top_i64() { return *reinterpret_cast<int64_t*>(&opstack_[sp_]); }
        int32_t& top_i32() { return *reinterpret_cast<int32_t*>(&opstack_[sp_]); }
        int64_t& below_i64() { return *reinterpret_cast<int64_t*>(&opstack_[sp_ - 8]); }
        int32_t& below_i32() { return *reinterpret_cast<int32_t*>(&opstack_[sp_ - 8]); }
        void push_i64(int64_t v) { sp_ += 8; *reinterpret_cast<int64_t*>(&opstack_[sp_]) = v; }
        void pop(int bytes) { sp_ -= bytes; }
    };
}

static std::string b64_encode(const uint8_t* data, size_t len) {
    static const char* chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string out;
    out.reserve(((len + 2) / 3) * 4);
    size_t i = 0;
    for (; i + 3 <= len; i += 3) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2];
        out.push_back(chars[(n >> 18) & 0x3F]);
        out.push_back(chars[(n >> 12) & 0x3F]);
        out.push_back(chars[(n >> 6) & 0x3F]);
        out.push_back(chars[n & 0x3F]);
    }
    size_t rem = len - i;
    if (rem == 1) {
        uint32_t n = data[i] << 16;
        out.push_back(chars[(n >> 18) & 0x3F]);
        out.push_back(chars[(n >> 12) & 0x3F]);
        out.push_back('='); out.push_back('=');
    }
    else if (rem == 2) {
        uint32_t n = (data[i] << 16) | (data[i + 1] << 8);
        out.push_back(chars[(n >> 18) & 0x3F]);
        out.push_back(chars[(n >> 12) & 0x3F]);
        out.push_back(chars[(n >> 6) & 0x3F]);
        out.push_back('=');
    }
    return out;
}

static std::vector<uint8_t> encrypt_vm_raw(const std::string& input, int32_t seed) {
    std::vector<uint8_t> buf(input.begin(), input.end());
    if (!buf.empty()) {
        grandvm::VM vm(bytecode, bytecodelen, buf.data(), static_cast<int32_t>(buf.size()), seed);
        vm.run();
    }
    return buf;
}

